"""Generate metrics/catalog.yaml and docs/suites.md from the registry (Plan.md §6)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from evalkit.registry import IMPLS, METRICS, SUITES, load_all


def catalog_data() -> dict[str, Any]:
    load_all()
    metrics = []
    for mid, spec in METRICS.items():
        engines = sorted({e for (m, e) in IMPLS if m == mid} | set(spec.engines))
        metrics.append(
            {
                "id": mid,
                "suites": list(spec.suites),
                "kind": spec.kind,
                "scope": spec.scope,
                "needs": list(spec.needs),
                "engines": engines,
                "direction": spec.direction,
                "unit": spec.unit,
                "description": spec.description,
                "requires_extra": spec.requires_extra,
            }
        )
    return {
        "generated_by": "evalctl catalog",
        "metrics": metrics,
        "suites": {
            name: (SUITES.get(name).__doc__ or "").strip().split("\n")[0] for name in SUITES.names()
        },
    }


def catalog_yaml() -> str:
    header = "# GENERATED by `evalctl catalog` from the metric registry. Do not edit.\n"
    return header + yaml.safe_dump(catalog_data(), sort_keys=False, allow_unicode=True, width=100)


def suites_markdown() -> str:
    data = catalog_data()
    lines = [
        "# Suites and metrics",
        "",
        "_Generated by `evalctl catalog` from the registry. Do not edit by hand._",
        "",
    ]
    for suite, doc in data["suites"].items():
        lines += [
            f"## `{suite}`",
            "",
            doc,
            "",
            "| metric | kind | scope | direction | unit | needs | engines | extra | description |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        for m in data["metrics"]:
            if suite in m["suites"]:
                lines.append(
                    f"| `{m['id']}` | {m['kind']} | {m['scope']} | {m['direction']} | "
                    f"{m['unit']} | {', '.join(m['needs']) or '–'} | {', '.join(m['engines'])} | "
                    f"{m['requires_extra'] or '–'} | "
                    f"{m['description'].replace('|', '/')} |"
                )
        lines.append("")
    cross = [m for m in data["metrics"] if "*" in m["suites"]]
    lines += [
        "## Cross-cutting (every suite's report)",
        "",
        "| metric | description |",
        "|---|---|",
    ]
    lines += [f"| `{m['id']}` | {m['description']} |" for m in cross]
    lines.append("")
    lines.append(f"Total: {len(data['metrics'])} metrics in {len(data['suites'])} suites.")
    return "\n".join(lines) + "\n"


def outputs(root: Path) -> dict[Path, str]:
    return {
        root / "metrics" / "catalog.yaml": catalog_yaml(),
        root / "docs" / "suites.md": suites_markdown(),
    }


def write_catalog(root: Path) -> list[Path]:
    written = []
    for path, text in outputs(root).items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def stale_files(root: Path) -> list[Path]:
    """Files whose content differs from what the registry generates."""
    return [
        p
        for p, text in outputs(root).items()
        if not p.exists() or p.read_text(encoding="utf-8") != text
    ]
